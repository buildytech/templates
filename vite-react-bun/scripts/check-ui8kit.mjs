import { createHash } from "node:crypto"
import { readFile } from "node:fs/promises"

const manifest = JSON.parse(await readFile(".ui8kit-manifest.json", "utf8"))
if (manifest.schemaVersion !== 1 || manifest.generator !== "@ui8kit/codegen") {
  throw new Error("Unsupported ui8kit manifest")
}
for (const entry of manifest.files) {
  const content = await readFile(entry.path)
  const digest = createHash("sha256").update(content).digest("hex")
  if (digest !== entry.sha256) {
    throw new Error(`Generated ui8kit file changed: ${entry.path}`)
  }
  if (
    entry.provenance
    && !content.toString("utf8").includes("Code generated by @ui8kit/codegen")
  ) {
    throw new Error(`Missing generated provenance: ${entry.path}`)
  }
}
console.log(`Verified ${manifest.files.length} generated ui8kit files`)
