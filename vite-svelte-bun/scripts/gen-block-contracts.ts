// Generates contracts/blocks.json from the props types of the installed registry blocks (src/blocks/*.svelte and
// their *.types.ts). The page contract (src/content/page.json) is checked against it by contract:validate.
// Run after `npx ui8kit add <block>`: bun run gen:contracts
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

type Field = { type: string; required: boolean; enum?: (string | number)[]; item?: Record<string, Field> }

const dir = "src/blocks"
const types = new Map<string, string>()
for (const f of readdirSync(dir).filter((f) => f.endsWith(".types.ts"))) {
  const src = readFileSync(join(dir, f), "utf8")
  for (const m of src.matchAll(/export type (\w+) = \{([\s\S]*?)\n\};/g)) types.set(m[1], m[2])
}

function parseFields(body: string): Record<string, Field> {
  const out: Record<string, Field> = {}
  for (const line of body.split("\n")) {
    const m = line.trim().match(/^"?([\w-]+)"?(\?)?:\s*(.+);$/)
    if (!m) continue
    const [, name, opt, raw] = m
    const t = raw.trim()
    const field: Field = { type: "string", required: !opt }
    if (/^("[^"]*"\s*\|\s*)*"[^"]*"$/.test(t)) {
      field.enum = [...t.matchAll(/"([^"]*)"/g)].map((x) => x[1])
    } else if (/^(\d+\s*\|\s*)*\d+$/.test(t)) {
      field.type = "number"
      field.enum = t.split("|").map((x) => Number(x.trim()))
    } else if (t.endsWith("[]")) {
      field.type = "array"
      const inner = t.slice(0, -2)
      if (types.has(inner)) field.item = parseFields(types.get(inner)!)
      else if (inner !== "string") field.type = "unknown"
    } else if (t === "number" || t === "boolean") {
      field.type = t
    } else if (t !== "string") {
      field.type = "unknown"
    }
    out[name] = field
  }
  return out
}

const items: Record<string, { component: string; props: Record<string, Field> }> = {}
for (const f of readdirSync(dir).filter((f) => f.endsWith(".svelte")).sort()) {
  const src = readFileSync(join(dir, f), "utf8")
  const m = src.match(/export type (\w+)Props = \{([\s\S]*?)\n  \};/)
  if (!m) continue
  items[f.replace(/\.svelte$/, "")] = { component: m[1], props: parseFields(m[2]) }
}
writeFileSync(
  "contracts/blocks.json",
  JSON.stringify({ $comment: "Generated by scripts/gen-block-contracts.ts from src/blocks. Do not edit.", items }, null, 2) + "\n",
)
console.log(`contracts/blocks.json: ${Object.keys(items).length} blocks`)
